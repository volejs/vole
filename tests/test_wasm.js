console.log("typeof WebAssembly:", typeof WebAssembly);

// WASM module that imports env.add(i32,i32)->i32 and exports call_add(i32,i32)->i32
const wasmBytes = new Uint8Array([
  0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00,
  0x01, 0x07, 0x01, 0x60, 0x02, 0x7f, 0x7f, 0x01, 0x7f,
  0x02, 0x0b, 0x01, 0x03, 0x65, 0x6e, 0x76, 0x03, 0x61, 0x64, 0x64, 0x00, 0x00,
  0x03, 0x02, 0x01, 0x00,
  0x07, 0x0c, 0x01, 0x08, 0x63, 0x61, 0x6c, 0x6c, 0x5f, 0x61, 0x64, 0x64, 0x00, 0x01,
  0x0a, 0x0a, 0x01, 0x08, 0x00, 0x20, 0x00, 0x20, 0x01, 0x10, 0x00, 0x0b
]);

const importObject = {
  env: {
    add: (a, b) => {
      console.log("JS add called:", a, b);
      return a + b;
    }
  }
};

const module = new WebAssembly.Module(wasmBytes);
const instance = new WebAssembly.Instance(module, importObject);
const result = instance.exports.call_add(10, 32);
console.log("call_add(10,32) =", result);

if (result !== 42) {
  throw new Error("Expected 42, got " + result);
}

console.log("WASM import test passed");
